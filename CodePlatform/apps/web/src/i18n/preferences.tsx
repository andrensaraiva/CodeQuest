type PreferencesContextValue = {
  language: Language
  theme: ColorTheme
  setLanguage: (language: Language) => void
  setTheme: (theme: ColorTheme) => void
  toggleTheme: () => void
  t: (key: keyof typeof pt) => string
  content: (value: string) => string
}

const PreferencesContext = createContext<PreferencesContextValue | null>(null)

function readStored<T extends string>(key: string, fallback: T, allowed: readonly T[]) {
  if (typeof window === 'undefined') return fallback
  const value = window.localStorage.getItem(key) as T | null
  return value && allowed.includes(value) ? value : fallback
}

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => readStored(LANGUAGE_KEY, 'pt-BR', ['pt-BR', 'en-US']))
  const [theme, setThemeState] = useState<ColorTheme>(() => readStored(THEME_KEY, 'dark', ['dark', 'light']))

  useEffect(() => {
    document.documentElement.lang = language
    window.localStorage.setItem(LANGUAGE_KEY, language)
  }, [language])

  useEffect(() => {
    document.documentElement.dataset.theme = theme
    window.localStorage.setItem(THEME_KEY, theme)
  }, [theme])

  const value = useMemo<PreferencesContextValue>(() => {
    const dictionary = language === 'pt-BR' ? pt : en
    return {
      language,
      theme,
      setLanguage: setLanguageState,
      setTheme: setThemeState,
      toggleTheme: () => setThemeState((current) => (current === 'dark' ? 'light' : 'dark')),
      t: (key) => dictionary[key],
      content: (text) => (language === 'pt-BR' ? contentPt[text] ?? text : text),
    }
  }, [language, theme])

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>
}

export function usePreferences() {
  const context = useContext(PreferencesContext)
  if (!context) {
    throw new Error('usePreferences must be used inside PreferencesProvider')
  }
  return context
}

export function roleLabel(role: string | undefined, t: PreferencesContextValue['t']) {
  if (role === 'Teacher') return t('common.teacher')
  if (role === 'Student') return t('common.student')
  if (role === 'Admin') return t('common.admin')
  return role ?? ''
}

export function statusLabel(status: string, t: PreferencesContextValue['t']) {
  if (status === 'Passed') return t('common.passed')
  if (status === 'Failed') return t('common.failed')
  return status
}
